#!/usr/bin/env python3
"""Generates src/import_returns.inc: the PS4 exports whose result says whether they failed, from
shadPS4's prototypes and their LIB_FUNCTION registrations.

    python3 tools/import_returns.py <shadPS4 checkout> > src/import_returns.inc

probe.c wraps an import the runtime binds to its own or the GPU library's function in a thunk that
records the calls that fail. Kinds: 1, an sce function returning a 32-bit result (a 0x8xxxxxxx
SCE error code on failure); 2 and 3, a POSIX function returning -1 with errno, as a 32-bit or a
64-bit result; 4, an sce function returning a 64-bit result (the SCE code sign-extended). A POSIX
function registered through ORBIS() returns SCE codes. Only exports whose arguments all travel in registers are listed (at most six, none
variadic, no structure by value), because the thunk calls the function with a stack of its own;
pthread functions, which return the error number itself, are left out.
"""
import re, sys
from pathlib import Path
from import_outparams import REGISTRATION, matching, split_params, strip_comments

PROTOTYPE = re.compile(r'([^\n;{}()]*?)\bPS4_SYSV_ABI\s+([A-Za-z_][\w:]*)\s*\(')
AGGREGATE = re.compile(r'(?<!enum )\b(?:struct|class|union)\s+(?:alignas\s*\([^)]*\)\s*)?([A-Za-z_]\w*)\s*(?:final\s*)?(?::[^{;]*)?\{')
TYPEDEF_AGGREGATE = re.compile(r'\btypedef\s+(?:struct|union)\b[^;]*?\}\s*([A-Za-z_]\w*)\s*;', re.S)
USING_AGGREGATE = re.compile(r'\busing\s+([A-Za-z_]\w*)\s*=\s*(?:struct|union|std::)')
SCE_RESULT = {'s32': 1, 'int': 1, 'int32_t': 1, 'Error': 1, 's64': 4, 'int64_t': 4}
POSIX_RESULT = {'s32': 2, 'int': 2, 'int32_t': 2, 's64': 3, 'ssize_t': 3, 'off_t': 3, 'int64_t': 3}


def result_type(prefix):
    words = [w for w in re.sub(r'\b(?:static|inline|extern|constexpr)\b', ' ', prefix).split()]
    return words[-1].split('::')[-1] if len(words) == 1 else None


def register_arguments(params, aggregates):
    if '...' in params:
        return False
    parts = split_params(params)
    if len(parts) > 6:
        return False
    for param in parts:
        type_ = re.sub(r'\b[A-Za-z_]\w*\s*(?:=.*)?$', '', param.split('=')[0].strip()).strip() or param
        if '*' in type_ or '&' in type_ or '[' in param:
            continue
        base = re.sub(r'\b(?:const|volatile|struct|enum|unsigned|signed)\b', '', type_).strip().split('::')[-1]
        if '<' in base or base in aggregates:
            return False
    return True


def kind_of(name, prefix, params, aggregates):
    """(kind as registered, kind as registered through ORBIS())."""
    result = result_type(prefix)
    if not result or not register_arguments(params, aggregates):
        return 0, 0
    if re.match(r'_?sce', name):
        return SCE_RESULT.get(result, 0), 0
    if name.startswith('posix_'):
        return 0 if name.startswith('posix_pthread_') else POSIX_RESULT.get(result, 0), SCE_RESULT.get(result, 0)
    return 0, 0


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: import_returns.py <shadPS4 checkout>')
    root = Path(sys.argv[1]) / 'src/core/libraries'
    if not root.is_dir():
        sys.exit(f'{root}: not a shadPS4 checkout')
    sources = [(path, strip_comments(path.read_text(errors='replace'))) for path in sorted(root.rglob('*'))
               if path.suffix in ('.cpp', '.h', '.hpp', '.inc')]
    aggregates = set()
    for _, text in sources:
        for pattern in (AGGREGATE, TYPEDEF_AGGREGATE, USING_AGGREGATE):
            aggregates.update(m.group(1) for m in pattern.finditer(text))
    kinds = {}
    for _, text in sources:
        for m in PROTOTYPE.finditer(text):
            name = m.group(2).split('::')[-1]
            close = matching(text, m.end() - 1, '(', ')')
            if close < 0:
                continue
            kinds.setdefault(name, set()).add(kind_of(name, m.group(1), text[m.end():close], aggregates))
    table = {}
    for path, text in sources:
        if path.suffix != '.cpp':
            continue
        for m in REGISTRATION.finditer(text):
            nid, function = m.group(1), m.group(2).strip()
            wrapped = re.fullmatch(r'ORBIS\(\s*([\w:]+)\s*\)', function)
            function = (wrapped.group(1) if wrapped else function).split('::')[-1]
            table.setdefault(nid, set()).update(kind[bool(wrapped)] for kind in kinds.get(function, {(0, 0)}))
    print('/* NID -> how the PS4 export reports a failure (1: 32-bit SCE error code, 2: -1 and errno as')
    print(' * a 32-bit result, 3: the same as a 64-bit result, 4: 64-bit SCE error code), for exports whose')
    print(' * arguments all travel in registers, sorted by NID in strcmp order for a binary search. Generated by')
    print(' * tools/import_returns.py from shadPS4\'s src/core/libraries; do not edit by hand. */')
    for nid in sorted(table, key=lambda n: n.encode()):
        if len(table[nid]) == 1 and 0 not in table[nid]:
            print(f'{{"{nid}",{next(iter(table[nid]))}}},')


if __name__ == '__main__':
    main()
